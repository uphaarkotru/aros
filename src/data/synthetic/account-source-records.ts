export interface SyntheticSourceBundle {
  account: SalesforceAccountRecord;
  stakeholders: StakeholderSourceRecord[];
  opportunities: SalesforceOpportunityRecord[];
  activities: ActivitySourceRecord[];
  usage: ProductUsageSourceRecord[];
  qualification: QualificationSourceRecord[];
  renewal: RenewalProfile;
  snapshots: AccountSnapshot[];
  initiatives: StrategicInitiative[];
  coverage: SourceCoverage[];
}
const bundle = (
  a: SalesforceAccountRecord,
  s: StakeholderSourceRecord[],
  o: SalesforceOpportunityRecord[],
  acts: ActivitySourceRecord[],
  u: ProductUsageSourceRecord[],
  q: QualificationSourceRecord[],
  r: RenewalProfile,
  previous: number,
  initiative: string,
): SyntheticSourceBundle => ({
  account: a,
  stakeholders: s,
  opportunities: o,
  activities: acts,
  usage: u,
  qualification: q,
  renewal: { ...r, renewalDate: a.RenewalDate, annualContractValue: a.ACV },
  snapshots: [
    {
      id: `old-${a.Id}`,
      accountId: a.Id,
      capturedAt: "2026-06-30T00:00:00.000Z",
      healthScore: previous,
      relationshipScore: previous,
      usageScore: previous,
      renewalLikelihood: r.renewalLikelihood + 0.08,
      openPipelineValue: o.reduce((x, y) => x + y.Amount, 0),
      meddpiccCompleteness: 50,
      activeRiskCount: 1,
      activeDecisionCount: 1,
      stakeholderEngagementSummary: "healthy",
    },
  ],
  initiatives: [
    {
      id: `initiative-${a.Id}`,
      accountId: a.Id,
      name: initiative,
      description: `${initiative} is a board-visible transformation program.`,
      executiveOwner: s[0]?.name ?? "Unknown",
      businessPriority: "high",
      status: "active",
      expectedTimeline: "FY2026",
      relatedUseCases: ["Revenue intelligence"],
      relatedProducts: ["AROS Intelligence"],
      relatedOpportunityIds: o.map((x) => x.Id),
      evidenceIds: [],
    },
  ],
  coverage: coverage(),
});
